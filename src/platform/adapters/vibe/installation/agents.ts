/**
 * Vibe native-agent sync — maps public rolebox roles to Vibe custom-agent
 * TOML files in `<vibeHome>/agents/`.
 *
 * Vibe discovers user-selectable agents from `~/.vibe/agents/<name>.toml`
 * (https://docs.mistral.ai/llms/vibe/code/cli/configuration-reference/
 * #agent-definition-files). Only PUBLIC roles become native agent files;
 * private children stay rolebox-internal execution targets, exactly as in
 * the Codex mapping. Writes are fingerprint-managed: a file whose content no
 * longer matches the recorded sha256 is preserved with a warning instead of
 * clobbered, and unmanaged files are never touched.
 */

import { createHash, randomUUID } from "node:crypto";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import type { ResolvedRole, ResolvedSubAgent } from "../../../../types.ts";
import { escapeTomlString } from "../../../managed-config-block.ts";

export interface VibeAgentDescriptor {
  roleId: string;
  rootRoleId: string;
  nativeName: string;
  displayName: string;
  description: string;
  instructions: string;
  parentId?: string;
  model?: string;
}

export interface VibeAgentMappings {
  agents: VibeAgentDescriptor[];
  warnings: string[];
}

const MANIFEST_NAME = "rolebox-agents.json";
const GENERATED_HEADER = "# Generated by rolebox. Edit role.yaml and sync again.\n";

/** Use readable names for ordinary IDs and a digest for case/path/Unicode collisions. */
export function vibeAgentName(roleId: string): string {
  if (roleId.length === 0) throw new Error("A Vibe rolebox agent requires a non-empty role ID");
  if (/^[a-z0-9][a-z0-9_-]{0,54}$/.test(roleId)) return `rolebox--${roleId}`;
  const slug = roleId.toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "agent";
  return `rolebox--${slug}-${digest(roleId).slice(0, 12)}`;
}

/**
 * Map a rolebox model to a Vibe `active_model` value: Vibe resolves models
 * by `[[models]]` alias or built-in model ID, so a bare ID projects as-is.
 * A provider-qualified `provider/model` value cannot be projected without
 * knowing the user's Vibe model presets, so it warns and is omitted.
 */
function mapModel(
  roleId: string,
  model: string | undefined,
  warnings: string[],
): string | undefined {
  const value = model?.trim();
  if (!value) return undefined;
  if (!value.includes("/")) return value;
  warnings.push(
    `Role '${roleId}': the provider-qualified model cannot be projected to a Vibe model alias; the native agent inherits the session's model. Use a bare Vibe model ID or [[models]] alias.`,
  );
  return undefined;
}

export function collectVibeAgentDescriptors(
  roles: readonly ResolvedRole[],
): VibeAgentMappings {
  const agents: VibeAgentDescriptor[] = [];
  const warnings: string[] = [];
  const ids = new Set<string>();
  const names = new Set<string>();
  function collect(agent: ResolvedRole | ResolvedSubAgent, rootRoleId: string, parentId?: string): void {
    const nativeName = vibeAgentName(agent.id);
    if (ids.has(agent.id) || names.has(nativeName)) throw new Error("Duplicate Vibe rolebox agent identity");
    ids.add(agent.id);
    names.add(nativeName);
    if (parentId !== undefined && "parentId" in agent && agent.parentId !== parentId) {
      throw new Error(`Role '${agent.id}' has an inconsistent parent identity`);
    }
    const config = agent.config;
    const context = [
      agent.prompt,
      "## Vibe rolebox mapping",
      `Your canonical rolebox agent ID is ${JSON.stringify(agent.id)}.`,
      "Vibe inherits approvals, tool permissions and model providers from the session; role instructions cannot grant additional authority.",
    ];
    if (agent.subagents.length > 0) {
      context.push(
        "Your private direct children remain rolebox execution targets, but this host exposes no session-execution transport for them:",
        ...agent.subagents.map(child => `- ${JSON.stringify(child.id)}: ${child.config.description}`),
        "Do not discover or address another role's private children.",
      );
    }
    const descriptor: VibeAgentDescriptor = {
      roleId: agent.id,
      rootRoleId,
      nativeName,
      displayName: config.name?.trim() || agent.id,
      description: config.description.trim() || `Run the ${config.name || agent.id} role.`,
      instructions: context.filter(Boolean).join("\n\n"),
      ...(parentId === undefined ? {} : { parentId }),
    };
    const model = mapModel(agent.id, config.model, warnings);
    if (model !== undefined) descriptor.model = model;
    if (config.temperature !== undefined || config.top_p !== undefined || config.variant !== undefined) {
      warnings.push(`Role '${agent.id}': Vibe agent files do not expose rolebox sampling parameters or model variants; they are omitted.`);
    }
    agents.push(descriptor);
    for (const child of agent.subagents) collect(child, rootRoleId, agent.id);
  }
  for (const role of roles) collect(role, role.id);
  return { agents, warnings };
}

export function renderVibeAgent(descriptor: VibeAgentDescriptor): string {
  const string = (value: string) => `"${escapeTomlString(value)}"`;
  const lines = [
    GENERATED_HEADER.trimEnd(),
    'agent_type = "agent"',
    `display_name = ${string(descriptor.displayName)}`,
    `description = ${string(descriptor.description)}`,
    `instructions = ${string(descriptor.instructions)}`,
  ];
  if (descriptor.model !== undefined) lines.push(`active_model = ${string(descriptor.model)}`);
  return `${lines.join("\n")}\n`;
}

interface ManagedAgentFile {
  name: string;
  sha256: string;
}

function digest(value: string): string {
  return createHash("sha256").update(value).digest("hex");
}

function readManifest(path: string): ManagedAgentFile[] {
  if (!pathExists(path)) return [];
  if (!lstatSync(path).isFile()) throw new Error("The Vibe rolebox agent manifest must be a regular file");
  const value: unknown = JSON.parse(readFileSync(path, "utf-8"));
  if (typeof value !== "object" || value === null || !("version" in value) || value.version !== 1 ||
    !("files" in value) || !Array.isArray(value.files)) throw new Error("Invalid Vibe rolebox agent manifest");
  const files: ManagedAgentFile[] = [];
  for (const entry of value.files) {
    if (typeof entry !== "object" || entry === null || typeof entry.name !== "string" ||
      !/^rolebox--[a-z0-9_-]+\.toml$/.test(entry.name) || typeof entry.sha256 !== "string" ||
      !/^[a-f0-9]{64}$/.test(entry.sha256) || files.some(file => file.name === entry.name)) {
      throw new Error("Invalid Vibe rolebox agent manifest entry");
    }
    files.push({ name: entry.name, sha256: entry.sha256 });
  }
  return files;
}

function sameManagedFile(path: string, previous: ManagedAgentFile | undefined): boolean {
  try {
    return previous !== undefined && lstatSync(path).isFile() &&
      digest(readFileSync(path, "utf-8")) === previous.sha256;
  } catch { return false; }
}

function pathExists(path: string): boolean {
  try { lstatSync(path); return true; } catch (error) {
    if (typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
}

function writeAtomic(path: string, content: string): void {
  const temporary = `${path}.${randomUUID()}.tmp`;
  try {
    writeFileSync(temporary, content, { encoding: "utf-8", flag: "wx", mode: 0o600 });
    renameSync(temporary, path);
  } finally {
    try { unlinkSync(temporary); } catch (error) {
      if (!(typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT")) throw error;
    }
  }
}

export interface SyncVibeAgentsOptions {
  vibeHome: string;
  /** Project roles belong to the project's own Vibe layer, never the global layer. */
  projectDir?: string;
}

export interface SyncVibeAgentsResult extends VibeAgentMappings {
  agentDir: string;
  manifestPath: string;
  written: number;
  removed: number;
}

/** Export public roles; private children remain runtime descriptors outside native discovery. */
export function syncVibeAgents(
  roles: readonly ResolvedRole[],
  options: SyncVibeAgentsOptions,
): SyncVibeAgentsResult {
  const mapping = collectVibeAgentDescriptors(roles);
  const configDir = options.projectDir === undefined ? options.vibeHome : join(options.projectDir, ".vibe");
  const agentDir = join(configDir, "agents");
  const manifestPath = join(configDir, MANIFEST_NAME);
  const previous = readManifest(manifestPath);
  const desired = mapping.agents.filter(agent => agent.parentId === undefined);
  const result: SyncVibeAgentsResult = { ...mapping, agentDir, manifestPath, written: 0, removed: 0 };
  if (desired.length === 0 && previous.length === 0) return result;
  if (pathExists(agentDir) && (!lstatSync(agentDir).isDirectory() || lstatSync(agentDir).isSymbolicLink())) {
    result.warnings.push("Vibe agents directory is not a regular directory; native agent files were preserved.");
    return result;
  }
  mkdirSync(agentDir, { recursive: true });
  const next = new Map<string, ManagedAgentFile>();
  const desiredNames = new Set(desired.map(agent => `${agent.nativeName}.toml`));
  for (const descriptor of desired) {
    const name = `${descriptor.nativeName}.toml`;
    const path = join(agentDir, name);
    const prior = previous.find(file => file.name === name);
    const content = renderVibeAgent(descriptor);
    if (pathExists(path) && !sameManagedFile(path, prior)) {
      result.warnings.push(`Native Vibe agent '${descriptor.nativeName}' has an unmanaged or edited file; it was preserved.`);
      if (prior !== undefined) next.set(name, prior);
      continue;
    }
    if (!pathExists(path) || readFileSync(path, "utf-8") !== content) {
      writeAtomic(path, content);
      result.written++;
    }
    next.set(name, { name, sha256: digest(content) });
  }
  for (const prior of previous) {
    if (desiredNames.has(prior.name)) continue;
    const path = join(agentDir, prior.name);
    if (!pathExists(path)) continue;
    if (sameManagedFile(path, prior)) {
      unlinkSync(path);
      result.removed++;
    } else {
      next.set(prior.name, prior);
      result.warnings.push(`Stale native Vibe agent '${prior.name}' has local changes; it was preserved.`);
    }
  }
  const manifest = `${JSON.stringify({ version: 1, files: [...next.values()].sort((a, b) => a.name.localeCompare(b.name)) }, null, 2)}\n`;
  if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf-8") !== manifest) writeAtomic(manifestPath, manifest);
  return result;
}
